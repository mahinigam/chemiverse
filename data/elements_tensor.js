function parseOxidationStates(str) {
  if (!str) return [];
  return str.split(',').map(s => {
    const m = s.trim().match(/([+-]?\d+)/);
    return m ? parseInt(m[1], 10) : 0;
  });
}

function inferNativeLattice(el) {
  const f = (el.allotrope_form || '').toLowerCase();
  if (f.includes('diamond')) return 'DC';
  if (f.includes('fcc') || f.includes('face centered')) return 'FCC';
  if (f.includes('hcp') || f.includes('hexagonal close')) return 'HCP';
  if (f.includes('bcc') || f.includes('body centered')) return 'BCC';
  if (f.includes('simple cubic')) return 'SC';
  return null;
}

function inferPhase(el) {
  const s = (el.state || 'Solid').toLowerCase();
  return ['solid', 'liquid', 'gas'].includes(s) ? s : 'solid';
}

