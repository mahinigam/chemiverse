// ---------------------------------------------------------------------------
// Build the immutable ELEMENTS_TENSOR (Subsystem A)
// ---------------------------------------------------------------------------
export const ELEMENTS_TENSOR = ELEMENTS_DATA.map(el => {
  const z = el.number;
  const base = el.atomic_radius != null ? el.atomic_radius / 100 : 0.30 + 0.18 * el.period;
  const ov = RADII_OVERRIDE[el.symbol];
  return {
    Z: z,
    symbol: el.symbol,
    name: el.name,
    category: el.category,
    mass: el.mass,
    group: el.group,
    period: el.period,
    block: el.block,
    shells: el.shells || [],
    electronConfigString: el.electron_config || '',
    chiPauling: el.electronegativity ?? null,
    chiAllen: (ALLEN_EN[z] || 0) > 0.05 ? ALLEN_EN[z] : (el.electronegativity ?? 0),
    ionizationEnergies: [0, I1[z] ?? 0, I2[z] ?? 0, I3[z] ?? 0, 0, 0, 0, 0],
    electronAffinity: EA[z] ?? 0,
    atomizationEnthalpy: ATOM_OVERRIDE[z] ?? ATOM[z] ?? 0,
    homonuclearBondEnergy: HBE[z] ?? 0,
    radii: {
      covalentSingle: ov ? ov[0] : base * 0.85,
      metallic: ov ? ov[1] : base * 0.95,
      vdw: ov ? ov[2] : base * 1.30,
      ionic: { ...(IONIC_RADII[z] || {}) },
    },
    oxStatePotentials: Object.fromEntries(
      Object.entries(POTENTIALS[z] || {}).map(([k, v]) => [parseInt(k, 10), v])
    ),
    allowedOxStates: parseOxidationStates(el.oxidation_states),
    miededa: MIEDEA[z] || null,
    stpPhase: inferPhase(el),
    nativeLattice: inferNativeLattice(el),
    allotropeForm: el.allotrope_form || el.state || '',
    meltingPointK: el.melting_point != null ? el.melting_point + 273.15 : null,
    boilingPointK: el.boiling_point != null ? el.boiling_point + 273.15 : null,
    density: el.density ?? null,
    standardEntropy: ENTROPY_OVERRIDE[z] ?? ENTROPY[z] ?? 0,
    color: el.color || '#cccccc',
    summary: el.summary || '',
  };
});

export function bySymbol(map) {
  const out = {};
  for (const e of ELEMENTS_TENSOR) out[e.symbol] = e;
  return out;
}
export const TENSOR_BY_SYMBOL = bySymbol(ELEMENTS_TENSOR);
export const TENSOR_BY_Z = new Map(ELEMENTS_TENSOR.map(e => [e.Z, e]));
